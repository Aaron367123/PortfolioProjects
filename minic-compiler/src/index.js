// index.js - the compiler driver: source text in, MIPS assembly out.
//
//   source -> lexer -> tokens -> parser -> AST -> semantic -> checked AST
//          -> [optimizer] -> codegen -> instructions -> [peephole] -> asm text
//
// compile() never throws for a bad program: every problem comes back as a
// diagnostic with a line and column. The compiler core does not import the
// emulator, so the same files work in Node (cli.js, tests) and in the browser.

import { tokenize } from './lexer.js';
import { parse } from './parser.js';
import { analyze } from './semantic.js';
import { optimize as optimizeAst } from './optimizer.js';
import { generate, printAsm } from './codegen.js';
import { peephole } from './peephole.js';
import { CompileError, diagnostic, formatDiagnostic } from './diagnostics.js';

export { formatDiagnostic } from './diagnostics.js';
export { tokenize } from './lexer.js';
export { parse } from './parser.js';

export const VERSION = '1.0.0';
const CODE_WORDS_LIMIT = 2048; // the emulator's code section: 0x0000-0x1FFF

/**
 * @param {string} source Mini-C program
 * @param {{ optimize?: boolean, peephole?: boolean }} [options]
 *   optimize: AST optimisations and peephole rules (-O1). Default true.
 *   peephole: override the peephole part separately (defaults to `optimize`).
 * @returns {{
 *   ok: boolean,
 *   asm: string|null,
 *   tokens: object[]|null,
 *   ast: object|null,            // checked AST (as parsed)
 *   optimizedAst: object|null,   // after the AST optimiser (same as ast at -O0)
 *   diagnostics: object[],       // { severity, message, line, col, length, text }
 *   lineMap: (number|null)[],    // lineMap[i] = Mini-C line that produced asm line i
 *   stats: object
 * }}
 */
export function compile(source, options = {}) {
  const optimize = options.optimize ?? true;
  const usePeephole = options.peephole ?? optimize;
  const started = now();
  const result = {
    ok: false, asm: null, tokens: null, ast: null, optimizedAst: null,
    diagnostics: [], lineMap: [], stats: { optimize, peephole: usePeephole },
  };
  const finish = () => {
    for (const d of result.diagnostics) d.text = formatDiagnostic(d, source);
    result.diagnostics.sort((a, b) => a.line - b.line || a.col - b.col);
    result.ok = result.asm !== null && !result.diagnostics.some((d) => d.severity === 'error');
    result.stats.timeMs = Math.round((now() - started) * 100) / 100;
    return result;
  };

  // 1-2. Lexing and parsing stop at the first syntax error.
  try {
    result.tokens = tokenize(source);
    result.ast = parse(result.tokens);
  } catch (err) {
    if (!(err instanceof CompileError)) throw err;
    result.diagnostics.push(diagnostic('error', err.message, err));
    return finish();
  }

  // 3. Semantic analysis reports every error it finds.
  const sema = analyze(result.ast);
  result.diagnostics.push(...sema.diagnostics);
  if (sema.diagnostics.some((d) => d.severity === 'error')) return finish();

  // 4. AST optimisations.
  let ast = result.ast;
  if (optimize) {
    const opt = optimizeAst(result.ast);
    ast = opt.ast;
    result.stats.optimizer = opt.stats;
  }
  result.optimizedAst = ast;

  // 5. Code generation, 6. peephole.
  const gen = generate(ast, source);
  let code = gen.code;
  const before = countInstructions(code);
  if (usePeephole) {
    const ph = peephole(code);
    code = ph.code;
    result.stats.peephole = ph.stats;
  }

  const header = [
    'Generated by the Mini-C compiler (minic-compiler) for the MIPS emulator',
    `Optimisation: ${optimize ? '-O1 (constant folding, simplification, peephole)' : '-O0 (none)'}`,
  ];
  const printed = printAsm(code, gen.data, header);
  result.asm = printed.asm;
  result.lineMap = printed.lineMap;

  const words = countWords(code);
  Object.assign(result.stats, {
    asmLines: printed.asm.split('\n').length - 1,
    instructions: countInstructions(code),
    instructionsBeforePeephole: before,
    words,                         // machine words after li expansion
    dataBytes: ast.dataBytes ?? 0,
    maxStackDepth: gen.maxDepth,
    spills: gen.spills,
    functions: ast.functions.length,
  });
  if (words > CODE_WORDS_LIMIT) {
    result.diagnostics.push(diagnostic('error', `the generated code is ${words} instructions, but the emulator's code section holds ${CODE_WORDS_LIMIT} (8 KB)`, { line: 1, col: 1 }));
  }
  return finish();
}

function countInstructions(code) {
  return code.filter((item) => item.type === 'ins').length;
}

/** `li` needs two words (lui + ori) when the constant does not fit in 16 bits. */
function countWords(code) {
  let words = 0;
  for (const item of code) {
    if (item.type !== 'ins') continue;
    if (item.op === 'li') {
      const v = Number(item.args[1]);
      words += (v >= -32768 && v <= 32767) || (v >= 0 && v <= 0xffff) ? 1 : 2;
    } else {
      words += 1;
    }
  }
  return words;
}

function now() {
  return typeof performance !== 'undefined' ? performance.now() : Date.now();
}
