#!/usr/bin/env node
/**
 * Builds the self-contained static demo: `npm run build:demo [-- --out <dir>]`
 *
 *   public/  -> <out>/          (dashboard)
 *   shared/  -> <out>/shared/   (the same logic modules the server runs, byte-identical)
 *   <out>/js/mode.js is rewritten to MODE = 'demo' so the page uses DemoSource.
 *
 * Default <out> is ../../demos/pet-monitor-live (the portfolio site's demo folder).
 * test/demo-sync.test.js checks the copied shared modules stay identical.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { ROOT_DIR } from '../server/settings.js';

const { values } = parseArgs({ options: { out: { type: 'string' } } });
const out = path.resolve(values.out ?? path.join(ROOT_DIR, '..', '..', 'demos', 'pet-monitor-live'));

if (path.basename(out) !== 'pet-monitor-live') throw new Error(`refusing to write to ${out} (expected a folder named pet-monitor-live)`);
if (path.resolve(out) === ROOT_DIR) throw new Error('output must not be the project itself');

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(ROOT_DIR, 'public'), out, { recursive: true });
fs.cpSync(path.join(ROOT_DIR, 'shared'), path.join(out, 'shared'), { recursive: true });
fs.writeFileSync(
  path.join(out, 'js', 'mode.js'),
  "// Generated by scripts/build-demo.js - static build, no server: run the pipeline in the browser.\nexport const MODE = 'demo';\n",
);

const count = (dir) => fs.readdirSync(dir, { recursive: true }).filter((f) => fs.statSync(path.join(dir, f)).isFile()).length;
console.log(`demo built: ${out} (${count(out)} files)`);
